// Bundles the website pages, CSS and database SQL into src/generated/assets.js so the
// serverless function always has them (no reliance on static-file hosting settings).
// Run after editing public/* or db/*:  npm run assets
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => fs.readFileSync(path.join(root, p), "utf8");
const pages = {};
for (const f of fs.readdirSync(path.join(root, "public")).sort())
  if (f.endsWith(".html") || f.endsWith(".css")) pages[f] = read(`public/${f}`);
const out = `// GENERATED by scripts/build-assets.js — do not edit by hand.\n` +
  `export const pages = ${JSON.stringify(pages, null, 0)};\n` +
  `export const schemaSql = ${JSON.stringify(read("db/schema.sql"))};\n` +
  `export const seedSql = ${JSON.stringify(read("db/seed.sql"))};\n`;
fs.mkdirSync(path.join(root, "src/generated"), { recursive: true });
const target = path.join(root, "src/generated/assets.js");
if (process.argv.includes("--verify")) {
  if (!fs.existsSync(target) || fs.readFileSync(target, "utf8") !== out) { console.error("assets.js is stale: run npm run assets"); process.exit(1); }
  console.log("assets up to date");
} else {
  fs.writeFileSync(target, out);
  console.log("wrote src/generated/assets.js");
}
